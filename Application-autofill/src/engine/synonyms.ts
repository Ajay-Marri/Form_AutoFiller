/**
 * Clean and normalize any raw identifier string
 */
export function normalizeIdentifier(rawText: string): string {
  if (!rawText) return '';
  return rawText
    .toLowerCase()
    .replace(/[_\W]+/g, ' ') // replace punctuation and underscores with space
    .replace(/([a-z])([A-Z])/g, '$1 $2') // camelCase split
    .trim();
}
